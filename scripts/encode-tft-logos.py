"""Encode supplied artwork as RGB565 runs for MCU flash (requires Pillow).

This is a build-time format conversion. Source artwork stays unchanged.
Generated artwork retains its original rights; it is not covered by the code MIT grant.
"""
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
assets = root / "qmarauder/web/assets"
lines = ["// Generated by scripts/encode-tft-logos.py. Artwork rights reserved.",
         "// See THIRD_PARTY_NOTICES.md. Original source images are unchanged.",
         "#pragma once", "#include <stdint.h>"]
for name, filename, bounds in [("bwm", "bwm.png", (72, 80)),
                              ("marauder", "marauder.webp", (48, 104))]:
    original = Image.open(assets / filename).convert("RGBA")
    fitted = ImageOps.contain(original, bounds, Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", bounds, (0, 0, 0, 255))
    canvas.alpha_composite(fitted, ((bounds[0]-fitted.width)//2, (bounds[1]-fitted.height)//2))
    pixels = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
              for r, g, b in canvas.convert("RGB").getdata()]
    runs = []
    for color in pixels:
        if runs and runs[-1][1] == color and runs[-1][0] < 65535:
            runs[-1][0] += 1
        else:
            runs.append([1, color])
    lines += [f"constexpr uint16_t {name}Width = {bounds[0]}, {name}Height = {bounds[1]};",
              f"const uint16_t {name}Runs[][2] = {{"]
    lines += ["  " + ",".join(f"{{{count},0x{color:04X}}}" for count, color in runs[i:i+8]) + ","
              for i in range(0, len(runs), 8)]
    lines.append("};")
target = root / "firmware/uno_shield/LogoData.h"
target.write_text("\n".join(lines) + "\n", encoding="ascii")
print(f"Encoded supplied logos: {target.name} ({target.stat().st_size} bytes of source)")
